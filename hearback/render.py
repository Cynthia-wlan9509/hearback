"""Markdown dashboard: threads grouped by status, plus a per-cluster summary."""
from __future__ import annotations

from hearback.config import Config
from hearback.ledger import triage_of
from hearback.util import now_iso, short, sid6

STATUS_ORDER = ["new", "investigating", "need-info", "fixed-pending-release", "released",
                "duplicate", "not-bug", "wontfix", "guide"]


def _cell(v: object) -> str:
    if isinstance(v, (list, tuple)):
        v = ", ".join(str(x) for x in v)
    return " ".join(str(v if v is not None else "").split()).replace("|", "\\|")


def thread_line(tid: str, rec: dict, claim: dict | None = None) -> str:
    """One compact line per thread: full id, status, cluster, [tags], title, author, rN, [@claimant].
    The full id is printed on purpose: the last six digits also work as a shorthand but can collide."""
    tri = triage_of(rec)
    return "%s %-21s %-20s [%s] %s — %s r%s%s" % (
        tid, tri.get("status", "new"), tri.get("cluster", "-"), ",".join(rec.get("tags", [])),
        short(rec.get("title", ""), 50), rec.get("author", ""), tri.get("rev", 0),
        "  @" + claim["by"] if claim else "")


def last_activity(rec: dict) -> str:
    times = [r.get("time") or "" for r in rec.get("replies") or []] + [rec.get("created") or ""]
    return max(times)[:10]


def render_dashboard(data: dict, cfg: Config | None = None) -> str:
    threads = data.get("threads", {})
    guild = data.get("guild_id", "")
    groups: dict[str, list[tuple[str, dict]]] = {}
    for tid in sorted(threads, key=int):
        groups.setdefault(triage_of(threads[tid]).get("status", "new"), []).append((tid, threads[tid]))
    order = [s for s in STATUS_ORDER if s in groups] + sorted(s for s in groups if s not in STATUS_ORDER)

    out = ["# Bug desk", "",
           "> Generated by `hearback render` at %s from the ledger (synced %s). Do not edit by hand."
           % (now_iso(), data.get("synced_at") or "never"), "",
           "**%d threads**: %s" % (len(threads), ", ".join("%s %d" % (s, len(groups[s])) for s in order) or "none"), ""]

    clusters: dict[str, list[dict]] = {}
    for tid, rec in threads.items():
        c = triage_of(rec).get("cluster")
        if c:
            clusters.setdefault(c, []).append(rec)
    if clusters:
        out += ["## Clusters", "", "| cluster | reports | statuses | fixed in |", "|---|---|---|---|"]
        for c in sorted(clusters, key=lambda k: (-len(clusters[k]), k)):
            recs = clusters[c]
            sts = sorted({triage_of(r).get("status", "new") for r in recs})
            fixed = sorted({triage_of(r).get("fixed_in") for r in recs if triage_of(r).get("fixed_in")})
            out.append("| %s | %d | %s | %s |" % (_cell(c), len(recs), _cell(sts), _cell(fixed)))
        out.append("")

    for st in order:
        rows = groups[st]
        out += ["## %s (%d)" % (st, len(rows)), "",
                "| thread | variants | title | author | cluster | root cause / fix | fixed in | last activity |",
                "|---|---|---|---|---|---|---|---|"]
        for tid, rec in rows:
            tri = triage_of(rec)
            link = "[%s](https://discord.com/channels/%s/%s)" % (sid6(tid), guild, tid) if guild else sid6(tid)
            variants = tri.get("variants") or [v.name for v in (cfg.variants.values() if cfg else [])
                                               if v.tag and v.tag in rec.get("tags", [])]
            why = " / ".join(str(x) for x in (tri.get("root_cause"), tri.get("fix")) if x)
            out.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (
                link, _cell(variants), _cell(rec.get("title")), _cell(rec.get("author")), _cell(tri.get("cluster")),
                _cell(short(why, 90)), _cell(tri.get("fixed_in")), last_activity(rec)))
        out.append("")
    return "\n".join(out)
