"""Reporter onboarding kit: a pinned "how to report a bug" forum post, with an optional annotated image.

The post text comes from the `guide_title` / `guide_body` templates. If Pillow is installed,
`--steps img.png:x,y,r:"caption" ...` turns screenshots into one strip with a red circle at (x, y)
of radius r on each step, numbered and captioned.
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import Sequence

from hearback import templates
from hearback.config import Config
from hearback.queue import Proposal, Queue
from hearback.util import HearbackError

STEP_RE = re.compile(r"^(?P<path>.+?):(?P<x>\d+),(?P<y>\d+),(?P<r>\d+):(?P<caption>.*)$", re.S)
FONT_CANDIDATES = ("msyh.ttc", "arial.ttf", "DejaVuSans.ttf", "Arial Unicode.ttf", "NotoSansCJK-Regular.ttc")


def parse_step(spec: str) -> dict:
    """`path:x,y,r:caption` -> dict. The path may contain a drive colon (C:\\shots\\a.png)."""
    m = STEP_RE.match(spec.strip())
    if not m:
        raise HearbackError("bad step %r; expected path:x,y,r:caption (pixels in the original image)" % spec)
    d = m.groupdict()
    return {"path": d["path"], "x": int(d["x"]), "y": int(d["y"]), "r": int(d["r"]),
            "caption": d["caption"].strip().strip('"')}


def _font(size: int):
    from PIL import ImageFont
    for name in FONT_CANDIDATES:
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            continue
    return ImageFont.load_default()


def _wrap(draw, text: str, font, width: int) -> list[str]:
    lines, cur = [], ""
    for ch in text:  # character wrapping works for both Latin and CJK text
        if draw.textlength(cur + ch, font=font) > width and cur:
            lines.append(cur)
            cur = ch.lstrip()
        else:
            cur += ch
    if cur:
        lines.append(cur)
    return lines or [""]


def make_steps(steps: Sequence[dict], out_path: str | Path, cell_w: int = 380, columns: int = 3) -> Path:
    """Render the annotated step strip. Needs Pillow."""
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        raise HearbackError("annotated step images need Pillow: pip install pillow (or pip install -e \".[images]\" from a clone)")
    if not steps:
        raise HearbackError("no steps given")
    pad, band = 14, 76
    font, small = _font(18), _font(15)
    cells = []
    for n, s in enumerate(steps, 1):
        try:
            im = Image.open(s["path"]).convert("RGB")
        except OSError as e:
            raise HearbackError("cannot open step image %s: %s" % (s["path"], e))
        scale = cell_w / im.width
        im = im.resize((cell_w, max(1, round(im.height * scale))))
        d = ImageDraw.Draw(im)
        cx, cy, r = s["x"] * scale, s["y"] * scale, max(4, s["r"] * scale)
        d.ellipse((cx - r, cy - r, cx + r, cy + r), outline=(230, 30, 30), width=4)
        cell = Image.new("RGB", (cell_w, im.height + band), "white")
        cell.paste(im, (0, 0))
        cd = ImageDraw.Draw(cell)
        cd.ellipse((4, im.height + 8, 32, im.height + 36), fill=(230, 30, 30))
        cd.text((12 if n < 10 else 7, im.height + 11), str(n), fill="white", font=small)
        for i, line in enumerate(_wrap(cd, s["caption"], small, cell_w - 48)[:3]):
            cd.text((40, im.height + 8 + i * 20), line, fill=(30, 30, 30), font=small)
        cells.append(cell)
    cols = min(columns, len(cells))
    rows = [cells[i:i + cols] for i in range(0, len(cells), cols)]
    row_h = [max(c.height for c in r) for r in rows]
    canvas = Image.new("RGB", (cols * cell_w + (cols + 1) * pad, sum(row_h) + (len(rows) + 1) * pad), (245, 245, 245))
    y = pad
    for r, h in zip(rows, row_h):
        for i, c in enumerate(r):
            canvas.paste(c, (pad + i * (cell_w + pad), y))
        y += h + pad
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    canvas.save(out, "PNG")
    return out


def variant_tag_names(cfg: Config) -> str:
    names = [v.tag or v.name for v in cfg.variants.values()]
    return ", ".join(names)


def propose_guide(queue: Queue, cfg: Config, actor: str, *, steps: Sequence[str] = (), tags: Sequence[str] = (),
                  pin: bool = True) -> Proposal:
    """Queue a newpost proposal containing the reporter tutorial (and the step strip, if requested)."""
    lang, tdir = cfg.language, cfg.templates_dir
    title = templates.render("guide_title", lang, tdir)
    body = templates.render("guide_body", lang, tdir, variant_tags=templates.trusted(
        variant_tag_names(cfg) or ("the build tag" if lang == "en" else "对应版本标签")))
    atts = []
    if steps:
        atts.append(str(make_steps([parse_step(s) for s in steps], cfg.data_dir / "guide" / "steps.png")))
    # the strip is generated by Hearback itself inside the data dir, which proposals otherwise may not attach from
    return queue.propose("newpost", actor=actor, thread=cfg.forum_id, title=title, text=body, add=list(tags),
                         attachments=atts, pin=pin, why="onboarding guide: how to report a bug",
                         meta={"guide": True}, trusted_attachments=True)
